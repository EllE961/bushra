/** The last three ajza' are known by their opening words. */
const JUZ_NAMES: Record<number, string> = { 28: "جزء قد سمع", 29: "جزء تبارك", 30: "جزء عمّ" };

export function juzName(n: number): string {
  return JUZ_NAMES[n] ?? `الجزء ${ORDINALS[n - 1]}`;
}

/** Folds the spellings people type interchangeably, for search. */
export function fold(s: string): string {
  return s
    .replace(/\p{M}|ـ/gu, "")
    .replace(/[أإآٱ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/ؤ/g, "و")
    .replace(/ئ/g, "ي")
    .replace(/[٠-٩]/g, (d) => String("٠١٢٣٤٥٦٧٨٩".indexOf(d)))
    .replace(/^(سوره|سورة)\s+/, "")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
}

/** "الناس" matches "ناس" and "الناس"; numbers match the surah number. */
export function surahMatches(index: number, query: string): boolean {
  const q = fold(query);
  if (!q) return true;
  if (/^\d+$/.test(q)) return String(index + 1).startsWith(q);
  const name = fold(SURAHS[index]);
  return name.includes(q) || name.replace(/^ال/, "").startsWith(q.replace(/^ال/, ""));
}
